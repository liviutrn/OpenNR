#!/usr/bin/env python3
"""Small real-git fixture tests for the source/generated-output boundary."""

from __future__ import annotations

import hashlib
import importlib.util
import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch


SCRIPT = Path(__file__).with_name("source_checkpoint.py")
SPEC = importlib.util.spec_from_file_location("source_checkpoint", SCRIPT)
assert SPEC is not None and SPEC.loader is not None
checkpoint = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(checkpoint)


def git(root: Path, *args: str) -> str:
    return subprocess.check_output(["git", "-C", str(root), *args], text=True).strip()


def write(root: Path, relative: str, data: str | bytes) -> Path:
    path = root / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data if isinstance(data, bytes) else data.encode("utf-8"))
    return path


def init_repo(path: Path) -> None:
    path.mkdir(parents=True, exist_ok=True)
    git(path, "init", "-q")
    git(path, "config", "user.name", "QuadView checkpoint test")
    git(path, "config", "user.email", "quadview-checkpoint@example.invalid")


class SourceCheckpointTests(unittest.TestCase):
    def setUp(self) -> None:
        self.temp = tempfile.TemporaryDirectory(prefix="quad-source-check-")
        self.root = Path(self.temp.name)
        self.backend = self.root / "backend"
        self.frontend = self.root / "frontend"
        self.sdk = self.backend / "dependencies/submodules/UESDK"
        init_repo(self.backend)
        init_repo(self.frontend)
        init_repo(self.sdk)

        write(self.sdk, "header.hpp", "stable SDK input\n")
        git(self.sdk, "add", "-A")
        git(self.sdk, "commit", "-qm", "fixture SDK")

        for relative in (
            "src/core.cpp",
            "tests/test.cpp",
            "CMakeLists.txt",
            "cmake.toml",
            "MakeCommitHash.bat",
            "src/mods/vr/shaders/alpha_luminance_sprite_ps.fx",
            "src/mods/vr/shaders/compile_shaders.bat",
            "src/mods/vr/shaders/Compiled/alpha_luminance_sprite_ps_SpritePixelShader.inc",
        ):
            write(self.backend, relative, "stable backend source\n")
        git(self.backend, "add", "src", "tests", "CMakeLists.txt", "cmake.toml", "MakeCommitHash.bat")
        git(self.backend, "commit", "-qm", "fixture backend")

        for relative in (
            "UEVR/hash_executables.py",
            "UEVR/UEVR.csproj",
            "tests/Program.cs",
        ):
            write(self.frontend, relative, "stable frontend source\n")
        write(self.frontend, "UEVR/PlainTextFilteredExecutables.json", '["Game.exe", "Other.exe"]')
        git(self.frontend, "add", "-A")
        git(self.frontend, "commit", "-qm", "fixture frontend")

        self.old_pins = checkpoint.PINS
        checkpoint.PINS = {
            "backend": git(self.backend, "rev-parse", "HEAD"),
            "frontend": git(self.frontend, "rev-parse", "HEAD"),
            "sdk": git(self.sdk, "rev-parse", "HEAD"),
        }
        write(
            self.backend,
            "src/CommitHash.autogenerated",
            f'#pragma once\n#define UEVR_COMMIT_HASH "{checkpoint.PINS["backend"]}" \n'
            f'#define UEVR_UESDK_COMMIT_HASH "{checkpoint.PINS["sdk"]}" \n'
            '#define UEVR_TRACKED_DIRTY "true" \n'
            '#define UEVR_UESDK_TRACKED_DIRTY "false" \n',
        )
        write(
            self.backend,
            "src/mods/vr/shaders/Compiled/alpha_luminance_sprite_ps_SpritePixelShader.pdb",
            b"pixel shader pdb",
        )
        write(
            self.backend,
            "src/mods/vr/shaders/Compiled/alpha_luminance_sprite_ps_SpriteVertexShader.pdb",
            b"vertex shader pdb",
        )
        self.write_filtered_output()

    def tearDown(self) -> None:
        checkpoint.PINS = self.old_pins
        self.temp.cleanup()

    def write_filtered_output(self) -> str:
        names = json.loads((self.frontend / "UEVR/PlainTextFilteredExecutables.json").read_text(encoding="utf-8"))
        output = json.dumps([hashlib.sha256(name.encode()).hexdigest().upper() for name in names], indent=4)
        write(self.frontend, "UEVR/FilteredExecutables.json", output)
        return output

    def test_generated_outputs_are_separate_from_source_hashes(self) -> None:
        actual = checkpoint.inspect(self.backend, self.frontend)
        self.assertIn("backend/MakeCommitHash.bat", actual["sha256"])
        self.assertIn(
            "backend/src/mods/vr/shaders/Compiled/alpha_luminance_sprite_ps_SpritePixelShader.inc",
            actual["sha256"],
        )
        self.assertFalse(set(actual["sha256"]) & set(checkpoint.GENERATED_OUTPUTS))
        record = checkpoint.verify_generated_outputs(self.backend, self.frontend, actual["sha256"])
        self.assertEqual(set(record["outputs"]), set(checkpoint.GENERATED_OUTPUTS))
        self.assertEqual(
            record["outputs"]["backend/src/CommitHash.autogenerated"]["identity_checks"]["UEVR_UESDK_TRACKED_DIRTY"],
            "false",
        )

    def test_generated_changes_are_hashed_without_masking_source_changes(self) -> None:
        before = checkpoint.inspect(self.backend, self.frontend)["sha256"]
        pdb = self.backend / "src/mods/vr/shaders/Compiled/alpha_luminance_sprite_ps_SpritePixelShader.pdb"
        before_output = hashlib.sha256(pdb.read_bytes()).hexdigest()
        pdb.write_bytes(b"recompiled pixel shader pdb")
        after = checkpoint.inspect(self.backend, self.frontend)["sha256"]
        self.assertEqual(before, after)
        after_output = checkpoint.verify_generated_outputs(self.backend, self.frontend, after)["outputs"][
            "backend/src/mods/vr/shaders/Compiled/alpha_luminance_sprite_ps_SpritePixelShader.pdb"
        ]["sha256"]
        self.assertNotEqual(before_output, after_output)

        write(self.backend, "src/core.cpp", "changed reviewed source\n")
        changed = checkpoint.inspect(self.backend, self.frontend)["sha256"]
        self.assertNotEqual(before["backend/src/core.cpp"], changed["backend/src/core.cpp"])

    def test_invalid_generated_frontend_resource_is_rejected(self) -> None:
        actual = checkpoint.inspect(self.backend, self.frontend)
        write(self.frontend, "UEVR/FilteredExecutables.json", "[]")
        with self.assertRaisesRegex(RuntimeError, "pinned generator output"):
            checkpoint.verify_generated_outputs(self.backend, self.frontend, actual["sha256"])

    def test_verify_writes_separate_generated_provenance_report(self) -> None:
        checkpoint_path = self.root / "evidence/quadview-source.json"
        checkpoint_path.parent.mkdir(parents=True)
        checkpoint_path.write_text(json.dumps(checkpoint.inspect(self.backend, self.frontend)), encoding="utf-8")
        with patch.object(sys, "argv", [str(SCRIPT), "verify", str(self.backend), str(self.frontend), str(checkpoint_path)]):
            checkpoint.main()
        report = checkpoint_path.with_name("quadview-source-generated.json")
        self.assertTrue(report.is_file())
        recorded = json.loads(report.read_text(encoding="utf-8"))
        self.assertEqual(set(recorded["outputs"]), set(checkpoint.GENERATED_OUTPUTS))

    def test_dirty_sdk_is_still_rejected(self) -> None:
        write(self.sdk, "unexpected.hpp", "untracked SDK change\n")
        with self.assertRaisesRegex(RuntimeError, "restricted SDK working tree changed"):
            checkpoint.inspect(self.backend, self.frontend)


if __name__ == "__main__":
    unittest.main(verbosity=2)
